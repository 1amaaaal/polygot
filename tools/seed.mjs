// Builds the SQL that fills the server's tables. Nothing here runs on the site.
//
//   node tools/seed.mjs languages > supabase/languages.sql
//       The clue traits, from data/languages.js. Public; commit it.
//
//   node tools/seed.mjs daily private/daily-snippets.txt --start 6 > private/daily-puzzles.sql
//       The daily puzzles. Days before --start keep the puzzles that were
//       played before the answers moved to the server (picked from
//       data/snippets.txt, as the site used to). From --start on, puzzles
//       come from the private file, which uses the same format as
//       data/snippets.txt and must never be committed: anyone who can read it
//       knows every answer. Re-running is safe; days already in the database
//       are left alone, so to add puzzles, run it again with a later --start.

import { readFileSync } from "node:fs";
import { LANGUAGES } from "../data/languages.js";
import { dailyOrder, dailySnippetIndex, parseSnippets, snippetProblem } from "../src/game.js";

const quote = (text) => `'${text.replaceAll("'", "''")}'`;
const lines = (snippet) => `array[${snippet.lines.map(quote).join(", ")}]::text[]`;

export function languagesSql(languages = LANGUAGES) {
  const rows = languages.map((l) =>
    `  (${[l.name, String(l.year), l.paradigm, l.typing, l.execution, l.family].map((v, i) => (i === 1 ? v : quote(v))).join(", ")})`);
  return [
    "-- The clue traits for every language that can be the answer. Generated by",
    "-- `node tools/seed.mjs languages` from data/languages.js; don't edit by hand.",
    "insert into public.languages (name, year, paradigm, typing, execution, family) values",
    rows.join(",\n"),
    "on conflict (name) do update set year = excluded.year, paradigm = excluded.paradigm, typing = excluded.typing,",
    "  execution = excluded.execution, family = excluded.family;",
    "",
  ].join("\n");
}

// The puzzle for each day: the old public schedule before `start`, then the
// private snippets in a seeded order that never repeats a language two days
// running (including across the switch).
export function dailyPuzzles({ publicSnippets, privateSnippets, start, seed = 7919 }) {
  const days = [];
  for (let day = 0; day < start; day++) days.push(publicSnippets[dailySnippetIndex(day, publicSnippets)]);
  const order = dailyOrder(privateSnippets, privateSnippets.length, seed).map((i) => privateSnippets[i]);
  // dailyOrder already avoids repeats inside the list; this also covers the
  // day the private puzzles start, after the last public one.
  let previous = days.at(-1)?.language;
  for (let i = 0; i < order.length; i++) {
    if (order[i].language === previous) {
      const j = order.findIndex((s, k) => k > i && s.language !== previous);
      if (j > 0) [order[i], order[j]] = [order[j], order[i]];
    }
    previous = order[i].language;
  }
  return [...days, ...order];
}

export function dailySql(puzzles, start) {
  const rows = puzzles.map((s, day) => `  (${day}, ${quote(s.language)}, ${lines(s)})`);
  return [
    "-- Daily puzzles: PRIVATE. Every answer is in this file, so keep it out of the",
    "-- repository. Paste it into the Supabase SQL editor after schema.sql and",
    `-- languages.sql. Days 0-${start - 1} are the puzzles already played; day ${start} on are new.`,
    "insert into private.daily_puzzles (day, language, lines) values",
    rows.join(",\n"),
    "on conflict (day) do nothing;",
    "",
  ].join("\n");
}

function main([command, file, ...rest]) {
  if (command === "languages") return process.stdout.write(languagesSql());
  if (command !== "daily" || !file) {
    console.error("usage: node tools/seed.mjs languages | daily <private-snippets.txt> --start <day>");
    process.exit(2);
  }
  const start = Number(rest[rest.indexOf("--start") + 1]);
  if (!Number.isInteger(start) || start < 0) {
    console.error("--start must be the first day number to take from the private file");
    process.exit(2);
  }
  const publicSnippets = parseSnippets(readFileSync(new URL("../data/snippets.txt", import.meta.url), "utf8"));
  const privateSnippets = parseSnippets(readFileSync(file, "utf8"));
  const known = new Set(publicSnippets.map((s) => s.lines.join("\n")));
  const problems = privateSnippets.flatMap((s) => {
    const problem = snippetProblem(s, LANGUAGES) ?? (known.has(s.lines.join("\n")) ? "is also in the public data/snippets.txt" : null);
    return problem ? [`${s.language} snippet starting "${s.lines[0]}" ${problem}`] : [];
  });
  if (problems.length) {
    console.error(problems.join("\n"));
    process.exit(1);
  }
  process.stdout.write(dailySql(dailyPuzzles({ publicSnippets, privateSnippets, start }), start));
  console.error(`${start} past puzzles and ${privateSnippets.length} new ones: days 0 to ${start + privateSnippets.length - 1}.`);
}

if (import.meta.url === `file://${process.argv[1]}`) main(process.argv.slice(2));
